-- Drop Table
BEGIN
  FOR t IN (SELECT column_value AS nome
            FROM TABLE(sys.odcivarchar2list('APOIO','OCORRENCIA','USUARIO','CATEGORIA','BAIRRO')))
  LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE ' || t.nome || ' CASCADE CONSTRAINTS';
    EXCEPTION
      WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;
    END;
  END LOOP;
END;
/

-- Create table

CREATE TABLE BAIRRO (
  ID_BAIRRO NUMBER GENERATED ALWAYS AS IDENTITY,
  NOME VARCHAR2(80) NOT NULL,
  
  CONSTRAINT PK_BAIRRO PRIMARY KEY (ID_BAIRRO),
  CONSTRAINT UK_BAIRRO_NOME UNIQUE (NOME)
);

CREATE TABLE CATEGORIA (
  ID_CATEGORIA NUMBER GENERATED ALWAYS AS IDENTITY,
  NOME VARCHAR2(80) NOT NULL,
  
  CONSTRAINT PK_CATEGORIA PRIMARY KEY (ID_CATEGORIA),
  CONSTRAINT UK_CATEGORIA_NOME UNIQUE (NOME)
);

CREATE TABLE USUARIO (
  ID_USUARIO NUMBER GENERATED ALWAYS AS IDENTITY,
  NOME VARCHAR2(100) NOT NULL,
  EMAIL VARCHAR2(120) NOT NULL,
  SENHA VARCHAR2(100) NOT NULL,
  TIPO VARCHAR2(10) NOT NULL,
  ID_BAIRRO NUMBER NOT NULL,
  
  CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
  CONSTRAINT UK_USUARIO_EMAIL UNIQUE (EMAIL),
  CONSTRAINT CK_USUARIO_TIPO CHECK (TIPO IN ('CIDADAO', 'AGENTE')),
  CONSTRAINT FK_USUARIO_BAIRRO FOREIGN KEY (ID_BAIRRO) REFERENCES BAIRRO (ID_BAIRRO)
);

CREATE TABLE OCORRENCIA (
  ID_OCORRENCIA NUMBER GENERATED ALWAYS AS IDENTITY,
  TITULO VARCHAR2(120) NOT NULL,
  DESCRICAO VARCHAR2(500),
  ENDERECO VARCHAR2(200) NOT NULL,
  STATUS VARCHAR2(15)  DEFAULT 'ABERTA' NOT NULL,
  DATA_ABERTURA DATE DEFAULT SYSDATE  NOT NULL,
  ID_USUARIO NUMBER NOT NULL,
  ID_CATEGORIA NUMBER NOT NULL,
  ID_BAIRRO NUMBER NOT NULL,
  
  CONSTRAINT PK_OCORRENCIA PRIMARY KEY (ID_OCORRENCIA),
  CONSTRAINT CK_OCORRENCIA_STATUS CHECK (STATUS IN ('ABERTA', 'EM_ANDAMENTO', 'RESOLVIDA')),
  CONSTRAINT FK_OCORRENCIA_USUARIO   FOREIGN KEY (ID_USUARIO)   REFERENCES USUARIO (ID_USUARIO),
  CONSTRAINT FK_OCORRENCIA_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA (ID_CATEGORIA),
  CONSTRAINT FK_OCORRENCIA_BAIRRO    FOREIGN KEY (ID_BAIRRO)    REFERENCES BAIRRO (ID_BAIRRO)
);

CREATE TABLE APOIO (
  ID_USUARIO NUMBER NOT NULL,
  ID_OCORRENCIA NUMBER NOT NULL,
  DATA_APOIO DATE DEFAULT SYSDATE NOT NULL,
  
  CONSTRAINT PK_APOIO PRIMARY KEY (ID_USUARIO, ID_OCORRENCIA),
  CONSTRAINT FK_APOIO_USUARIO FOREIGN KEY (ID_USUARIO)
    REFERENCES USUARIO (ID_USUARIO) ON DELETE CASCADE,
  CONSTRAINT FK_APOIO_OCORRENCIA FOREIGN KEY (ID_OCORRENCIA)
    REFERENCES OCORRENCIA (ID_OCORRENCIA) ON DELETE CASCADE
);

