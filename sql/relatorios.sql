-- Script de Consutas

-- Consulta 1 
SELECT b.NOME AS BAIRRO, COUNT(o.ID_OCORRENCIA) AS TOTAL
FROM BAIRRO b
JOIN OCORRENCIA o ON o.ID_BAIRRO = b.ID_BAIRRO
GROUP BY b.ID_BAIRRO, b.NOME
ORDER BY b.ID_BAIRRO;

-- Consulta 2 
SELECT c.NOME AS CATEGORIA, COUNT(o.ID_OCORRENCIA) AS TOTAL
FROM CATEGORIA c
JOIN OCORRENCIA o ON o.ID_CATEGORIA = c.ID_CATEGORIA
GROUP BY c.ID_CATEGORIA, c.NOME
ORDER BY c.ID_CATEGORIA;

-- Consulta 3
SELECT o.TITULO, b.NOME AS BAIRRO, o.STATUS, COUNT(a.ID_USUARIO) AS TOTAL_APOIOS
FROM OCORRENCIA o
JOIN BAIRRO b ON b.ID_BAIRRO = o.ID_BAIRRO
LEFT JOIN APOIO a ON a.ID_OCORRENCIA = o.ID_OCORRENCIA
GROUP BY o.ID_OCORRENCIA, o.TITULO, b.NOME, o.STATUS
ORDER BY TOTAL_APOIOS DESC, o.ID_OCORRENCIA;

-- Consulta 4
SELECT STATUS, COUNT(*) AS TOTAL
FROM OCORRENCIA
GROUP BY STATUS
ORDER BY STATUS;
