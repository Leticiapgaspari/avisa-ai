-- Relatórios (usados pelo RelatorioDaoJdbc)

-- Por bairro: bairro sem ocorrência aparece com 0
SELECT b.NOME,
       COUNT(o.ID_OCORRENCIA) AS TOTAL
FROM BAIRRO b
LEFT JOIN OCORRENCIA o ON o.ID_BAIRRO = b.ID_BAIRRO
GROUP BY b.NOME
ORDER BY TOTAL DESC, b.NOME;

-- Por categoria: categoria sem ocorrência aparece com 0
SELECT c.NOME,
       COUNT(o.ID_OCORRENCIA) AS TOTAL
FROM CATEGORIA c
LEFT JOIN OCORRENCIA o ON o.ID_CATEGORIA = c.ID_CATEGORIA
GROUP BY c.NOME
ORDER BY TOTAL DESC, c.NOME;

-- Por status
SELECT o.STATUS,
       COUNT(*) AS TOTAL
FROM OCORRENCIA o
GROUP BY o.STATUS
ORDER BY TOTAL DESC, o.STATUS;

-- Mais apoiadas: ocorrência sem apoio aparece com 0
SELECT o.ID_OCORRENCIA,
       o.TITULO,
       b.NOME AS BAIRRO,
       o.STATUS,
       COUNT(a.ID_USUARIO) AS TOTAL_APOIOS
FROM OCORRENCIA o
JOIN BAIRRO b ON b.ID_BAIRRO = o.ID_BAIRRO
LEFT JOIN APOIO a ON a.ID_OCORRENCIA = o.ID_OCORRENCIA
GROUP BY o.ID_OCORRENCIA, o.TITULO, b.NOME, o.STATUS, o.DATA_ABERTURA
ORDER BY TOTAL_APOIOS DESC, o.DATA_ABERTURA DESC;
